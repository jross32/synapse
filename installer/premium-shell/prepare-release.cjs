'use strict';
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'../..'),shell=__dirname;
const pkg=JSON.parse(fs.readFileSync(path.join(root,'package.json'),'utf8'));
const version=pkg.version;
if(!/^\d+\.\d+\.\d+$/.test(version))throw Error('Invalid application version');
const source=path.join(root,'release','Synapse Setup '+version+'.exe');
if(!fs.existsSync(source))throw Error('Current-version Synapse NSIS installer missing: '+source);
const name=path.basename(source),target=path.join(shell,'payload',name);
fs.mkdirSync(path.dirname(target),{recursive:true});fs.copyFileSync(source,target);
const sha256=crypto.createHash('sha256').update(fs.readFileSync(target)).digest('hex');
fs.writeFileSync(path.join(shell,'payload-manifest.json'),JSON.stringify({filename:name,version,sha256},null,2)+'\n');
const shellPkg=JSON.parse(fs.readFileSync(path.join(shell,'package.json'),'utf8'));
shellPkg.version=version;
shellPkg.build.extraResources=[{from:'payload/'+name,to:'synapse-payload/'+name}];
fs.writeFileSync(path.join(shell,'package.json'),JSON.stringify(shellPkg,null,2)+'\n');
console.log('Prepared embedded '+name+' SHA256 '+sha256);
