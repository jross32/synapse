'use strict';
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=__dirname,errors=[];
const pkg=require('./package.json');const manifest=require('./payload-manifest.json');
const main=fs.readFileSync(path.join(root,'host-chatgpt.cjs'),'utf8');
const ui=fs.readFileSync(path.join(root,'installer.js'),'utf8');
const p=path.join(root,'payload',manifest.filename);
if(!fs.existsSync(p))errors.push('Embedded NSIS payload is missing');
else if(crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex')!==manifest.sha256)errors.push('Embedded payload SHA256 mismatch');
if(pkg.version!==manifest.version)errors.push('Shell version does not match payload');
if(!pkg.build.extraResources?.some(x=>x.to==='synapse-payload/'+manifest.filename))errors.push('Bundled payload not configured');
if(main.includes('pickPayload'))errors.push('External installer file picker still used');
if(!main.includes('findInstalled()'))errors.push('Installed executable is not verified');
if(ui.includes('state.signedIn = true'))errors.push('False sign-in success in wizard');
if(!main.includes("['/S']"))errors.push('NSIS installer is not invoked silently');
const output=path.resolve(root,'../../release-premium-shell');
if(!fs.existsSync(output)||!fs.readdirSync(output).some(n=>n.endsWith('.exe')&&n.includes(manifest.version)))errors.push('Version-matched single distributable not built');
console.log('Synapse premium packaging gate: '+(errors.length?'BLOCKED':'PASS (packaging only, Windows E2E and signing not included)'));
for(const e of errors)console.error('BLOCKER: '+e);
if(errors.length)process.exitCode=1;
