from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

BASELINE_KEY = "workflow:baseline"
CHALLENGER_KEY = "workflow:ui-forge"

BASELINE_INSTRUCTION = """Benchmark treatment: ordinary workflow.
Execute the benchmark task using the supplied project and normal tools. Do not invoke, read, or use the UI Forge skill pack or UI Forge helper scripts. You may inspect/run/test the app and use normal browser/development tools. Preserve the task requirements and produce the requested artifacts. The task brief below is the shared benchmark task and must not be altered."""

CHALLENGER_INSTRUCTION = """Benchmark treatment: UI Forge.
Use the installed Synapse skill pack `ui-forge` and its machine-readable workflow contract. Treat the running application as the deliverable. Inspect before editing, preserve product truth/behavior, plan bounded changes, use browser proof, source precision tooling when relevant, score the result, repair only the highest-leverage root cause, and persist friction. Produce the requested benchmark artifacts. The task brief below is the shared benchmark task and must not be altered."""


def _load_spec(path: str | Path) -> dict[str, Any]:
    payload = json.loads(Path(path).read_text(encoding="utf-8"))
    if not isinstance(payload, dict) or not isinstance(payload.get("scenarios"), list):
        raise ValueError("benchmark spec must be a JSON object with scenarios")
    return payload


def build_matrix(
    spec: dict[str, Any],
    *,
    runtime_id: str,
    provider: str,
    model: str,
    surface_kind: str,
    scenario_ids: list[str] | None = None,
) -> list[dict[str, Any]]:
    known = [str(item.get("id")) for item in spec["scenarios"] if item.get("id")]
    selected = scenario_ids or known
    unknown = sorted(set(selected) - set(known))
    if unknown:
        raise ValueError(f"unknown scenario ids: {', '.join(unknown)}")
    matrix: list[dict[str, Any]] = []
    for scenario_id in selected:
        common = {
            "scenario_id": scenario_id,
            "runtime_id": runtime_id,
            "provider": provider,
            "model": model,
            "surface_kind": surface_kind,
        }
        matrix.append(
            {
                **common,
                "metadata": {
                    "candidate_group_key": BASELINE_KEY,
                    "candidate_instruction_md": BASELINE_INSTRUCTION,
                    "workflow_treatment": "baseline",
                },
            }
        )
        matrix.append(
            {
                **common,
                "metadata": {
                    "candidate_group_key": CHALLENGER_KEY,
                    "candidate_instruction_md": CHALLENGER_INSTRUCTION,
                    "workflow_treatment": "ui-forge",
                },
            }
        )
    return matrix


def build_run_payload(
    spec_path: str | Path,
    *,
    project_id: str,
    runtime_id: str,
    provider: str,
    model: str,
    surface_kind: str = "synapse_coder_thread",
    repeat_count: int = 5,
    scenario_ids: list[str] | None = None,
    title: str | None = None,
) -> dict[str, Any]:
    if repeat_count < 1:
        raise ValueError("repeat_count must be at least 1")
    spec = _load_spec(spec_path)
    spec_id = str(spec.get("id") or "").strip()
    if not spec_id:
        raise ValueError("benchmark spec id is required")
    return {
        "spec_id": spec_id,
        "project_id": project_id,
        "title": title or f"UI Forge same-model benchmark · {model or runtime_id}",
        "execution_mode": "serial",
        "repeat_count": repeat_count,
        "notes_md": (
            "Generated by UI Forge. Baseline and challenger share the same benchmark task, "
            "runtime/model/surface; candidate_instruction_md is the declared workflow treatment."
        ),
        "matrix": build_matrix(
            spec,
            runtime_id=runtime_id,
            provider=provider,
            model=model,
            surface_kind=surface_kind,
            scenario_ids=scenario_ids,
        ),
        "metadata": {
            "comparison": "same-model-workflow-treatment",
            "baseline_candidate_key": BASELINE_KEY,
            "challenger_candidate_key": CHALLENGER_KEY,
        },
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate a Synapse benchmark run payload for baseline vs UI Forge")
    default_spec = Path(__file__).resolve().parents[1] / "references" / "benchmark-spec.json"
    parser.add_argument("--spec", default=str(default_spec))
    parser.add_argument("--project-id", required=True)
    parser.add_argument("--runtime", required=True)
    parser.add_argument("--provider", default="")
    parser.add_argument("--model", default="")
    parser.add_argument("--surface", default="synapse_coder_thread")
    parser.add_argument("--repeats", type=int, default=5)
    parser.add_argument("--scenario", action="append")
    parser.add_argument("--title")
    parser.add_argument("--output")
    args = parser.parse_args(argv)
    try:
        payload = build_run_payload(
            args.spec,
            project_id=args.project_id,
            runtime_id=args.runtime,
            provider=args.provider,
            model=args.model,
            surface_kind=args.surface,
            repeat_count=args.repeats,
            scenario_ids=args.scenario,
            title=args.title,
        )
        serialized = json.dumps(payload, indent=2, sort_keys=True) + "\n"
        if args.output:
            target = Path(args.output)
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(serialized, encoding="utf-8")
        print(serialized, end="")
        return 0
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        print(json.dumps({"error": str(exc)}, indent=2))
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
